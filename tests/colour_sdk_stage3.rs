//! `SPEC-099` AC8 (`DEC-087`): red and blue register to Adobe `dng_validate -3`.
//!
//! The SDK's stage 3 is camera RGB over the `ActiveArea` after `OpcodeList3`'s
//! per-plane `WarpRectilinear`. Ours is the CA step (the tests' own reference of
//! `DEC-087` item 3, `tests/support/ca_reference.rs`, which `tests/leica_colour.rs`
//! AC7 ties to `srgb_linear_plane_into` at every sample) followed by
//! `apply_warp_into` with the consumer's warp (`sensor_geometry_warp(..).consumer()`,
//! green's set). The measure is the radial component of the Lucas–Kanade shift
//! (6 iterations, bilinear, patch means removed) between 160×160 patches at
//! eight positions: `(±0.85, ±0.85)` of the half-extent, `(±0.92, 0)` and
//! `(0, ±0.9)`, placed inside the `DefaultCrop`.
//!
//! **The baseline** is ours with no CA step against an SDK run on a copy whose
//! red and blue sets are overwritten by green's (`<tag>-green.tif`): the same
//! warp on every plane, so only the demosaic and the kernel differ. Pre-registered
//! (SPEC-099 Implementation Context), for each file, red and blue, every patch:
//! - `|shift(CA + green, SDK full) − shift(green-only, SDK green)| ≤ 0.10 px`;
//! - **red-proof:** `|shift(green-only, SDK full) − shift(green-only, SDK green)|
//!   ≥ 0.30 px`, so a reference that skipped the CA step fails the first bound.
//!
//! The patches never reach the SL3's bad columns (9528 to 9535, outside its
//! crop), so `n` here applies no bad-pixel fix: `n = min(⌊max(raw − 512, 0)·65535
//! / (16383 − 512) + 0.5⌋, 65535)` on all three files.
//!
//! `SPEC-100` AC9 (`DEC-088`) adds the developed outputs: the colour develop's
//! camera triple (the same construction, which `tests/leica_colour.rs` AC7 ties
//! to `develop_color_into` at every sample) with green within 0.01 px of its
//! baseline as well, and the developed mix (`develop_with_into`'s default
//! output, un-oriented) against the SDK's stage 3 mixed in `f64` by
//! `mono_mix_row` (`Σ q_c·cam_c / 2^24`), its baseline the same on the
//! green-only copy (`<tag>-green.dng`): within 0.10 px at every patch.
//!
//! **Tier B plus `$IRRADIANCE_SDK_STAGE3_DIR`**, local only, generated by
//! `scripts/sdk-stage3.sh`; a SKIP line when unset (always in CI), and each file
//! is skipped by name when absent. ⚠ The Q3 and SL3 have no stated licence: no
//! file, SDK output or derived pixel from them is ever committed.

