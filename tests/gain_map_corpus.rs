        let (aw, ah) = active_size(&sensor);
        let mut full_at_one = vec![0u16; (aw as usize) * (ah as usize)];
        let at_one = develop_with_into(&sensor, &plane, &mut full_at_one, &full_warped);
        if FULL_WARP_REFUSED.contains(&path) {
            assert!(
                matches!(at_one, Err(Error::UnsupportedWarpedFullActiveArea { .. })),
                "{path}: FullActiveArea at warp_alpha 1.0 must be refused (DEC-059): {at_one:?}"
            );
        } else {
            assert!(
                at_one.is_ok(),
                "{path}: FullActiveArea at warp_alpha 1.0: {at_one:?}"
            );
        }
        let mut full_options = full_warped;
        full_options.warp_alpha = 0.0;
        let (fw, fh, full) = develop_mono(&sensor, &plane, &full_options);
        assert_eq!(
            (fw, fh),
            active_size(&sensor),
            "{path}: FullActiveArea size"
        );
        got[2] = md5_u16(&full);

        // Colour, all four entries; threaded equals single-thread.
        let mut rgb = vec![0u16; (w as usize) * (h as usize) * 3];
        develop_color_into(&sensor, &plane, &mut rgb).unwrap_or_else(|e| panic!("{path}: {e}"));
