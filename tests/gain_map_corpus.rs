/// The held file's sensor and unpacked raw plane, or `None` (skip, by name).
fn corpus_plane(path: &str) -> Option<(Sensor, Vec<u16>)> {
    let manifest = Manifest::load().expect("tests/corpus/manifest.toml must parse");
    let root = CorpusRoot::resolve();
    let entry = manifest
        .get(path)
        .unwrap_or_else(|| panic!("{path} must be in the manifest"));
    let file_path = entry.require(&root)?;
    let bytes = std::fs::read(&file_path).unwrap_or_else(|e| panic!("{path}: read: {e}"));
    let container = Container::parse(&bytes).unwrap_or_else(|e| panic!("{path}: {e}"));
    let sensor = container.sensor().unwrap_or_else(|e| panic!("{path}: {e}"));
    let mut plane = vec![0u16; (sensor.width as usize) * (sensor.height as usize)];
    unpack_into(&sensor, container.byte_order(), &bytes, &mut plane)
        .unwrap_or_else(|e| panic!("{path}: unpack: {e}"));
    Some((sensor, plane))
}

/// The sensor with `OpcodeList2` removed: the same develop with no `GainMap`.
fn without_gain(sensor: &Sensor) -> Sensor {
    let mut s = sensor.clone();
    s.opcode_list_2 = None;
    s
}

/// `ActiveArea`'s size (the plane's when the tag is absent).
fn active_size(sensor: &Sensor) -> (u32, u32) {
    match sensor.active_area {
        Some(a) => (a.right - a.left, a.bottom - a.top),
        None => (sensor.width, sensor.height),
    }
}

/// MD5 of `u16` samples as little-endian bytes (`tests/develop_options.rs`'s
/// pin encoding).
fn md5_u16(samples: &[u16]) -> String {
    let bytes: Vec<u8> = samples.iter().flat_map(|s| s.to_le_bytes()).collect();
    md5::to_hex(&md5::hash(&bytes))
}

/// MD5 of `f32` samples as little-endian IEEE bit patterns.
fn md5_f32(samples: &[f32]) -> String {
    let bytes: Vec<u8> = samples
        .iter()
        .flat_map(|s| s.to_bits().to_le_bytes())
        .collect();
    md5::to_hex(&md5::hash(&bytes))
}

/// `PerPosition` black, otherwise default (`StandardCrop`, oriented, full warp).
fn per_position(framing: Framing) -> DevelopOptions {
    let mut o = DevelopOptions::default();
    o.framing = framing;
    o.black_levels = BlackLevels::PerPosition;
    o
}

/// The SDK-comparable mono develop: the whole `ActiveArea`, stored order, no
/// warp (the SDK's stage 2 is before `OpcodeList3`), per-position black.
fn stage2_like() -> DevelopOptions {
    let mut o = per_position(Framing::FullActiveArea);
    o.apply_orientation = false;
    o.warp_alpha = 0.0;
    o
}

fn develop_mono(sensor: &Sensor, plane: &[u16], options: &DevelopOptions) -> (u32, u32, Vec<u16>) {
    let (w, h) = output_dimensions_with(sensor, options).expect("dimensions");
    let mut dst = vec![0u16; (w as usize) * (h as usize)];
    develop_with_into(sensor, plane, &mut dst, options).expect("develop_with_into");
    (w, h, dst)
}

