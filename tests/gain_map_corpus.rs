/// Signed differences `reference − ours`.
struct Diff {
    samples: usize,
    exact: usize,
    max_abs: u32,
    min: i32,
    max: i32,
    histogram: BTreeMap<i32, usize>,
}

impl Diff {
    fn of(reference: &[u16], ours: &[u16]) -> Diff {
        assert_eq!(
            reference.len(),
            ours.len(),
            "compared images differ in size"
        );
        let mut histogram = BTreeMap::new();
        for (&r, &o) in reference.iter().zip(ours) {
            *histogram.entry(i32::from(r) - i32::from(o)).or_insert(0) += 1;
        }
        let min = *histogram.keys().next().unwrap_or(&0);
        let max = *histogram.keys().next_back().unwrap_or(&0);
        Diff {
            samples: reference.len(),
            exact: histogram.get(&0).copied().unwrap_or(0),
            max_abs: min.unsigned_abs().max(max.unsigned_abs()),
            min,
            max,
            histogram,
        }
    }
    fn exact_fraction(&self) -> f64 {
        self.exact as f64 / self.samples as f64
    }
    fn report(&self, label: &str) -> String {
        format!(
            "{label}: max|d| {} (min {}, max {}), exact {}/{} = {:.4}%, histogram {:?}",
            self.max_abs,
            self.min,
            self.max,
            self.exact,
            self.samples,
            100.0 * self.exact_fraction(),
            self.histogram
        )
    }
}

/// The SDK output directory, or `None` with a visible SKIP line. Its status is
/// also printed by `examples/corpus-status.rs`, which `just test` runs first,
/// because `cargo test` captures a passing test's `eprintln!`.
fn sdk_dir() -> Option<PathBuf> {
    match std::env::var_os(SDK_STAGE2_ENV) {
        Some(d) if !d.is_empty() => Some(PathBuf::from(d)),
        _ => {
            eprintln!(
                "SKIP dng_validate cross-check — ${SDK_STAGE2_ENV} unset \
                 (generate it with scripts/sdk-stage2.sh)"
            );
            None
        }
    }
}

/// One SDK stage-2 TIFF. The directory was set on purpose, so a missing or
/// malformed file is a failure, not a skip.
fn sdk_stage2(dir: &std::path::Path, stem: &str, which: &str) -> stage2_tiff::Stage2 {
    let p = dir.join(format!("{stem}-{which}.tif"));
    let bytes = std::fs::read(&p).unwrap_or_else(|e| {
        panic!(
            "{}: {e} — ${SDK_STAGE2_ENV} is set, so scripts/sdk-stage2.sh's outputs must be there",
            p.display()
        )
    });
    stage2_tiff::read(&bytes).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

/// `AC4`, the gate: `apply_gain_maps` on the SDK's own pre-gain stage 2, with
/// the file's `OpcodeList2`, against the SDK's post-gain stage 2. Pre-registered:
/// max |d| ≤ 1 and at least 99.9% exact, on every file.
const GAIN_STEP_MAX_ABS: u32 = 1;
const GAIN_STEP_MIN_EXACT: f64 = 0.999;
/// `AC5`, end to end: mono `stage2_like()` against the SDK's post-gain stage 2.
const END_TO_END_MAX_ABS: u32 = 8;
/// `AC5`, root cause: the same develop with no `GainMap` against the SDK's
/// pre-gain stage 2.
const NO_GAIN_MAX_ABS: u32 = 5;
/// Files whose no-gain differences are all `≥ 0` (SDK at or above us: its
/// `white − max black` scale). The 7 Pro's rounded black sits below the SDK's
/// fractional one (`DEC-068`), so its differences are mostly negative.
const NO_GAIN_NON_NEGATIVE: [&str; 2] = ["GOOGLE-PIXEL-4A", "GOOGLE-PIXEL-3A"];

#[test]
fn gain_step_matches_dng_validate_stage_2() {
    let Some(dir) = sdk_dir() else { return };
    for (path, stem) in PIXELS {
        let Some((sensor, _)) = corpus_plane(path) else {
            continue; // SKIP announced by name by CorpusFile::require
        };
        let list = sensor
            .opcode_list_2
            .as_deref()
            .unwrap_or_else(|| panic!("{path}: no OpcodeList2"));
        let mut pre = sdk_stage2(&dir, stem, "pre");
        let post = sdk_stage2(&dir, stem, "post");
        assert_eq!(
            (pre.width, pre.height),
            active_size(&sensor),
            "{stem}: SDK stage 2 is ActiveArea-sized"
        );
        assert_eq!((post.width, post.height), (pre.width, pre.height));
        assert!(
            pre.samples != post.samples,
            "{stem}: the SDK's pre and post are identical"
        );

        let applied = apply_gain_maps(&mut pre.samples, pre.width, pre.height, list)
            .unwrap_or_else(|e| panic!("{stem}: apply_gain_maps: {e}"));
        assert_eq!(applied, 4, "{stem}: four GainMaps, one per Bayer phase");

        let d = Diff::of(&post.samples, &pre.samples);
        eprintln!("SDK GAIN STEP {}", d.report(stem));
        assert!(
            d.max_abs <= GAIN_STEP_MAX_ABS && d.exact_fraction() >= GAIN_STEP_MIN_EXACT,
            "{}",
            d.report(&format!(
                "{stem}: gain step outside max|d| <= {GAIN_STEP_MAX_ABS}, exact >= {}%",
                100.0 * GAIN_STEP_MIN_EXACT
            ))
        );
    }
}

#[test]
fn end_to_end_and_no_gain_are_within_their_bounds() {
    let Some(dir) = sdk_dir() else { return };
    for (path, stem) in PIXELS {
        let Some((sensor, plane)) = corpus_plane(path) else {
            continue; // SKIP announced by name by CorpusFile::require
        };
        let pre = sdk_stage2(&dir, stem, "pre");
        let post = sdk_stage2(&dir, stem, "post");

        let (w, h, ours) = develop_mono(&sensor, &plane, &stage2_like());
        assert_eq!((w, h), (post.width, post.height), "{stem}: size");
        let end_to_end = Diff::of(&post.samples, &ours);
        eprintln!("SDK END TO END {}", end_to_end.report(stem));

        let (_, _, ours_plain) = develop_mono(&without_gain(&sensor), &plane, &stage2_like());
        let no_gain = Diff::of(&pre.samples, &ours_plain);
        eprintln!("SDK NO GAIN {}", no_gain.report(stem));

        assert!(
            end_to_end.max_abs <= END_TO_END_MAX_ABS,
            "{}",
            end_to_end.report(&format!("{stem}: end to end over {END_TO_END_MAX_ABS}"))
        );
        assert!(
            no_gain.max_abs <= NO_GAIN_MAX_ABS,
            "{}",
            no_gain.report(&format!("{stem}: no-gain over {NO_GAIN_MAX_ABS}"))
        );
        if NO_GAIN_NON_NEGATIVE.contains(&stem) {
            assert!(
                no_gain.min >= 0,
                "{}",
                no_gain.report(&format!("{stem}: a no-gain difference is negative"))
            );
        }
    }
}
