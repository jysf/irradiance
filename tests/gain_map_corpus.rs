        develop_color_into_threaded(&sensor, &plane, &mut rgb_threaded, THREADS)
            .unwrap_or_else(|e| panic!("{path}: {e}"));
        assert!(rgb == rgb_threaded, "{path}: threaded colour u16 differs");
        got[3] = md5_u16(&rgb);

        let mut rgbf = vec![0f32; rgb.len()];
        develop_color_f32_into(&sensor, &plane, &mut rgbf)
            .unwrap_or_else(|e| panic!("{path}: {e}"));
        let mut rgbf_threaded = vec![0f32; rgb.len()];
