/// A hand-built stage-2-shaped TIFF: one IFD, `entries` as
/// `(tag, type, count, value)` with SHORT values left-aligned in the field,
/// pixel data at offset `8 + 2 + 12·n + 4`.
fn hand_tiff(little: bool, entries: &[(u16, u16, u32, u32)], data: &[u8]) -> Vec<u8> {
    let u16b = |v: u16| {
        if little {
            v.to_le_bytes()
        } else {
            v.to_be_bytes()
        }
    };
    let u32b = |v: u32| {
        if little {
            v.to_le_bytes()
        } else {
            v.to_be_bytes()
        }
    };
    let mut out = Vec::new();
    out.extend_from_slice(if little { b"II" } else { b"MM" });
    out.extend_from_slice(&u16b(42));
    out.extend_from_slice(&u32b(8));
    out.extend_from_slice(&u16b(entries.len() as u16));
    for &(tag, ty, count, value) in entries {
        out.extend_from_slice(&u16b(tag));
        out.extend_from_slice(&u16b(ty));
        out.extend_from_slice(&u32b(count));
        if ty == 3 && count == 1 {
            out.extend_from_slice(&u16b(value as u16));
            out.extend_from_slice(&[0, 0]);
        } else {
            out.extend_from_slice(&u32b(value));
        }
    }
    out.extend_from_slice(&u32b(0));
    out.extend_from_slice(data);
    out
}

/// The six entries of a 3×2 16-bit stage-2 image, with `compression`,
/// `samples` and `bits` substitutable for the refusal cases.
fn stage2_entries(n: u32, compression: u32, samples: u32, bits: u32) -> Vec<(u16, u16, u32, u32)> {
    let data_at = 8 + 2 + 12 * n + 4;
    vec![
        (256, 4, 1, 3),
        (257, 4, 1, 2),
        (258, 3, 1, bits),
        (259, 3, 1, compression),
        (273, 4, 1, data_at),
        (277, 3, 1, samples),
        (279, 4, 1, 12),
    ]
}

const READER_SAMPLES: [u16; 6] = [0x0001, 0x0203, 0xFFFF, 0x8000, 0x1234, 0x00FF];

fn sample_bytes(little: bool) -> Vec<u8> {
    READER_SAMPLES
        .iter()
        .flat_map(|s| {
            if little {
                s.to_le_bytes()
            } else {
                s.to_be_bytes()
            }
        })
        .collect()
}

#[test]
fn stage2_reader_reads_both_byte_orders() {
    for little in [true, false] {
        let tiff = hand_tiff(little, &stage2_entries(7, 1, 1, 16), &sample_bytes(little));
        let img = stage2_tiff::read(&tiff).unwrap_or_else(|e| panic!("little={little}: {e}"));
        assert_eq!((img.width, img.height), (3, 2), "little={little}");
        assert_eq!(img.samples, READER_SAMPLES, "little={little}");
    }
}

#[test]
fn stage2_reader_refuses_other_shapes() {
    let data = sample_bytes(true);
    let cases: [(&str, Vec<u8>); 6] = [
        (
            "Compression 7",
            hand_tiff(true, &stage2_entries(7, 7, 1, 16), &data),
        ),
        (
            "SamplesPerPixel 3",
            hand_tiff(true, &stage2_entries(7, 1, 3, 16), &data),
        ),
        (
            "BitsPerSample 8",
            hand_tiff(true, &stage2_entries(7, 1, 1, 8), &data),
        ),
        ("byte-order mark", {
            let mut t = hand_tiff(true, &stage2_entries(7, 1, 1, 16), &data);
            t[0] = b'X';
            t
        }),
        // One byte short of 3×2×2.
        (
            "run past the end",
            hand_tiff(true, &stage2_entries(7, 1, 1, 16), &data[..11]),
        ),
        ("tiled TIFF", {
            let mut e = stage2_entries(8, 1, 1, 16);
            e.push((322, 4, 1, 16));
            hand_tiff(true, &e, &data)
        }),
    ];
    for (want, tiff) in cases {
        match stage2_tiff::read(&tiff) {
            Ok(_) => panic!("{want}: accepted"),
            Err(e) => assert!(e.contains(want), "{want}: refused with {e:?}"),
        }
    }
}

/// `SPEC-060` verify: `dng_validate` writes one strip, so the reader's
/// multi-strip path is reached only here. Two one-row strips, stored in the
/// file in reverse order (row 1 first), so a reader that ignored
/// `StripOffsets` or read only the first strip would fail. Both byte orders.
#[test]
fn stage2_reader_joins_strips_in_offset_order() {
    for little in [true, false] {
        let u32b = |v: u32| {
            if little {
                v.to_le_bytes()
            } else {
                v.to_be_bytes()
            }
        };
        // Seven entries; `data` starts at 8 + 2 + 12·7 + 4 = 98. It holds the
        // two-entry offsets array (98), the counts array (106), row 1 (114)
        // and row 0 (120).
        let data_at = 98u32;
        let rows = sample_bytes(little);
        let mut data = Vec::new();
        data.extend_from_slice(&u32b(data_at + 22));
        data.extend_from_slice(&u32b(data_at + 16));
        data.extend_from_slice(&u32b(6));
        data.extend_from_slice(&u32b(6));
        data.extend_from_slice(&rows[6..]);
        data.extend_from_slice(&rows[..6]);
        let mut entries = stage2_entries(7, 1, 1, 16);
        for e in &mut entries {
            match e.0 {
                273 => *e = (273, 4, 2, data_at),
                279 => *e = (279, 4, 2, data_at + 8),
                _ => {}
            }
        }
        let tiff = hand_tiff(little, &entries, &data);
        let img = stage2_tiff::read(&tiff).unwrap_or_else(|e| panic!("little={little}: {e}"));
        assert_eq!((img.width, img.height), (3, 2), "little={little}");
        assert_eq!(img.samples, READER_SAMPLES, "little={little}");
    }
}

