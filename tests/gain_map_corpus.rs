/// Side of the square windows, in stage-2 pixels (even, so a window holds a
/// whole number of 2×2 Bayer cells).
const WINDOW: u32 = 128;

/// Mean of CFA phase (row 0, column 0) — the `ActiveArea`'s top-left
/// photosite colour — over the `WINDOW`-square at `(top, left)` (both even).
fn phase00_mean(img: &[u16], width: u32, top: u32, left: u32) -> f64 {
    let mut sum = 0f64;
    let mut n = 0f64;
    for r in (top..top + WINDOW).step_by(2) {
        for c in (left..left + WINDOW).step_by(2) {
            sum += f64::from(img[(r * width + c) as usize]);
            n += 1.0;
        }
    }
    sum / n
}

/// Corner-to-centre ratio of CFA phase (0, 0): the mean of the four corner
/// windows over the mean of the centre window.
fn corner_to_centre(img: &[u16], w: u32, h: u32) -> f64 {
    let even = |v: u32| v & !1;
    let corners = [
        (0, 0),
        (0, even(w - WINDOW)),
        (even(h - WINDOW), 0),
        (even(h - WINDOW), even(w - WINDOW)),
    ];
    let corner = corners
        .iter()
        .map(|&(t, l)| phase00_mean(img, w, t, l))
        .sum::<f64>()
        / 4.0;
    let centre = phase00_mean(img, w, even((h - WINDOW) / 2), even((w - WINDOW) / 2));
    corner / centre
}

/// The phase-(0,0) `GainMap`'s gain grid, parsed **by hand** from the raw
/// `OpcodeList2` bytes (DNG 1.7 Chapter 7, big-endian): list count, then per
/// opcode `id, version, flags, size` and its parameters. `GainMap` (id 9)
/// parameters are `Top, Left, Bottom, Right, Plane, Planes, RowPitch,
/// ColPitch, MapPointsV, MapPointsH` (u32), `MapSpacingV/H, MapOriginV/H`
/// (f64), `MapPlanes` (u32), then the `f32` gains. Independent of the crate's
/// parser on purpose (AGENTS.md §16 rule 5). Returns `(points_v, points_h,
/// gains)` for the map whose `Top` and `Left` are both 0.
fn phase00_map(list: &[u8]) -> (usize, usize, Vec<f32>) {
    let u32_at = |at: usize| u32::from_be_bytes(list[at..at + 4].try_into().unwrap());
    let count = u32_at(0) as usize;
    let mut at = 4;
    let mut found = Vec::new();
    for _ in 0..count {
        let (id, size) = (u32_at(at), u32_at(at + 12) as usize);
        let p = at + 16;
        if id == 9 && u32_at(p) == 0 && u32_at(p + 4) == 0 {
            let (v, h) = (u32_at(p + 32) as usize, u32_at(p + 36) as usize);
            let gains = (0..v * h)
                .map(|i| {
                    f32::from_be_bytes(list[p + 76 + 4 * i..p + 80 + 4 * i].try_into().unwrap())
                })
                .collect();
            found.push((v, h, gains));
        }
        at = p + size;
    }
    assert_eq!(found.len(), 1, "exactly one GainMap anchored at (0, 0)");
    found.remove(0)
}

/// Corner gain (the mean of the grid's four corner entries) and centre gain
/// (the mean of the one, two or four entries nearest the grid's centre) of a
/// row-major `v × h` grid.
fn map_corner_and_centre(v: usize, h: usize, g: &[f32]) -> (f64, f64) {
    let at = |r: usize, c: usize| f64::from(g[r * h + c]);
    let corner = (at(0, 0) + at(0, h - 1) + at(v - 1, 0) + at(v - 1, h - 1)) / 4.0;
    let rows = if v % 2 == 1 {
        vec![v / 2]
    } else {
        vec![v / 2 - 1, v / 2]
    };
    let cols = if h % 2 == 1 {
        vec![h / 2]
    } else {
        vec![h / 2 - 1, h / 2]
    };
    let mut sum = 0.0;
    for &r in &rows {
        for &c in &cols {
            sum += at(r, c);
        }
    }
    (corner, sum / (rows.len() * cols.len()) as f64)
}

/// `AC2` (as amended at build, `SPEC-060`): the `GainMap` changes the output
/// in its correction direction. (1) The output differs from the same develop
/// with `opcode_list_2 = None`. (3) The parsed phase-(0,0) map's corner gain
/// exceeds its centre gain, which anchors (2) to the map, not the scene.
/// (2) On every file the phase-(0,0) corner/centre ratio rises. (4) It moves
/// toward 1 only where it started below 1: on a scene whose corners are
/// already brighter (the 4a), lifting them moves the ratio away from 1.
#[test]
fn pixel_gain_map_lifts_the_corners_relative_to_the_centre() {
    for (path, _) in PIXELS {
        let Some((sensor, plane)) = corpus_plane(path) else {
            continue; // SKIP announced by name by CorpusFile::require
        };
        let (w, h, gained) = develop_mono(&sensor, &plane, &stage2_like());
        let (_, _, plain) = develop_mono(&without_gain(&sensor), &plane, &stage2_like());
        assert!(gained != plain, "{path}: GainMap changed nothing");

        let list = sensor.opcode_list_2.as_deref().expect("OpcodeList2");
        let (pv, ph, grid) = phase00_map(list);
        let (map_corner, map_centre) = map_corner_and_centre(pv, ph, &grid);
        assert!(
            map_corner > map_centre,
            "{path}: phase (0,0) map corner gain {map_corner:.4} <= centre {map_centre:.4}"
        );

        let with = corner_to_centre(&gained, w, h);
        let without = corner_to_centre(&plain, w, h);
        eprintln!(
            "PIXEL VIGNETTE ({path}): phase (0,0) map {pv}x{ph}, corner gain {map_corner:.4}, \
             centre gain {map_centre:.4}; corner/centre {without:.4} without the GainMap, \
             {with:.4} with it"
        );
        assert!(
            with > without,
            "{path}: corner/centre ratio {without:.4} -> {with:.4} did not rise"
        );
        if without < 1.0 {
            assert!(
                (with - 1.0).abs() < (without - 1.0).abs(),
                "{path}: corner/centre ratio {without:.4} -> {with:.4} did not move toward 1"
            );
        }
    }
}

