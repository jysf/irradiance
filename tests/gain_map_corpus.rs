        let (w, h) = output_dimensions(&sensor).expect("dimensions");
        assert_eq!(
            output_dimensions_with(&sensor, &DevelopOptions::default()).expect("dimensions"),
            (w, h),
            "{path}: output_dimensions_with(default)"
        );
        let mut mono = vec![0u16; (w as usize) * (h as usize)];
        develop_into(&sensor, &plane, &mut mono).unwrap_or_else(|e| panic!("{path}: {e}"));
        got[0] = md5_u16(&mono);

        // Mono, PerPosition, both framings.
        let (sw, sh, standard) =
            develop_mono(&sensor, &plane, &per_position(Framing::StandardCrop));
        assert_eq!((sw, sh), (w, h), "{path}: StandardCrop size");
        got[1] = md5_u16(&standard);
        // `FullActiveArea` at the default full warp is refused where the
        // file's `OpcodeList3` `WarpRectilinear` could sample outside the
        // image (`DEC-059` §3). Measured per file at this build: the 3a is
        // refused, the 4a and 7 Pro develop `Ok`. Each file's outcome is
        // asserted exactly. The pinned framing runs with the warp off
        // (`warp_alpha: 0.0`), which `DEC-059` always accepts.
