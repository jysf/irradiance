//! Generate `src/tone_table.rs` — the committed sRGB OETF (IEC 61966-2-1)
//! encode tables (`SPEC-019`, `DEC-025`).
//!
//! This is the **one place `powf` is allowed to run**: here, at generation
//! time, on the maintainer's machine, producing committed bytes that are then
//! byte-identical for everyone (`AC4`/`AC7`). The library itself (`src/tone.rs`)
//! does an integer lookup into these tables and never calls a transcendental on
//! the encode path.
//!
//! Mirrors `examples/fuzz-seeds.rs`: an example plus a `just` recipe
//! (`just gen-tone-table`) regenerates committed data from its source of truth.
//! Each table is annotated `#[rustfmt::skip]` so this file's own 16-per-line
//! layout is the format of record — `cargo fmt --check` (a CI gate) leaves the
//! arrays untouched, and `just gen-tone-table`'s `git diff --exit-code`
//! reproduces them with no diff.
//!
//! ```text
//! just gen-tone-table        # rewrite src/tone_table.rs, assert no diff
//! ```
//!
//! The sRGB OETF, scene-linear `L ∈ [0, 1]` → display-referred `V ∈ [0, 1]`:
//!
//! ```text
//! V = 12.92·L                        for L ≤ 0.0031308
//! V = 1.055·L^(1/2.4) − 0.055        otherwise
//! ```
//!
//! Table index `i` is the scene-linear `u16`; `L = i / 65535.0`. `V` is scaled
//! to the output range (`×65535` or `×255`), **rounded to nearest** (consistent
//! with `DEC-018`'s rounding rule), and clamped into range.

use std::fmt::Write as _;
use std::path::PathBuf;

/// The sRGB opto-electronic transfer function (IEC 61966-2-1).
fn srgb_oetf(l: f64) -> f64 {
    if l <= 0.0031308 {
        12.92 * l
    } else {
        1.055 * l.powf(1.0 / 2.4) - 0.055
    }
}

/// Encode table index `i` to an integer code value on `[0, full_scale]`,
/// round-to-nearest, clamped.
fn encode(i: u32, full_scale: f64) -> u32 {
    let l = f64::from(i) / 65535.0;
    let v = srgb_oetf(l).clamp(0.0, 1.0);
    (v * full_scale).round() as u32
}

/// Render one const array, 16 values per line.
///
/// `#[rustfmt::skip]` keeps this layout as the format of record (`cargo fmt
/// --check` is a CI gate). `#[allow(clippy::large_const_arrays)]` is the one
/// non-policy lint this file allows, and it is deliberate: the lint would have
/// us make these `static`, but a `const` is exactly what `SPEC-019` requires —
/// determinism (`DEC-002`/`AC7`) wants committed const data, and `AC4`'s
/// proof that the tables are const reads them in a `const` context, which a
/// `static` cannot satisfy. None of the five panic-policy lints
/// (`no-panics-on-untrusted-input`) is touched, so `just lint-no-allow` stays
/// green.
fn render_array(name: &str, elem_type: &str, values: &[String]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "#[allow(clippy::large_const_arrays)] // see DEC-025: const is required by AC4/determinism, not static");
    let _ = writeln!(
        out,
        "pub(crate) const {name}: [{elem_type}; 65536] = ["
    );
    for chunk in values.chunks(16) {
        out.push_str("    ");
        out.push_str(&chunk.join(", "));
        out.push_str(",\n");
    }
    out.push_str("];\n");
    out
}

fn main() {
    let table16: Vec<String> = (0u32..=65535)
        .map(|i| (encode(i, 65535.0) as u16).to_string())
        .collect();
    let table8: Vec<String> = (0u32..=65535)
        .map(|i| (encode(i, 255.0) as u8).to_string())
        .collect();

    let mut src = String::new();
    src.push_str(
        "// src/tone_table.rs — GENERATED by `examples/gen-tone-table.rs`. DO NOT EDIT BY HAND.\n\
         //\n\
         // Committed sRGB OETF (IEC 61966-2-1) encode tables (`SPEC-019`, `DEC-025`).\n\
         // Regenerate with:\n\
         //\n\
         //     just gen-tone-table\n\
         //\n\
         // Index `i` is a scene-linear u16; L = i / 65535.0; V = sRGB_OETF(L); the stored\n\
         // value is V scaled to the output range, round-to-nearest, clamped (`DEC-018`\n\
         // rounding rule). `powf` runs only in the generator; the library does an integer\n\
         // lookup here and calls no transcendental on the encode path (`AC4`). Each array is\n\
         // `#[rustfmt::skip]` so this layout is the format of record and `cargo fmt --check`\n\
         // (a CI gate) leaves it alone.\n\n",
    );
    src.push_str(&render_array("SRGB_ENCODE_16", "u16", &table16));
    src.push('\n');
    src.push_str(&render_array("SRGB_ENCODE_8", "u8", &table8));

    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("src")
        .join("tone_table.rs");
    if let Err(e) = std::fs::write(&path, &src) {
        eprintln!("gen-tone-table: {e}");
        std::process::exit(1);
    }
    println!(
        "gen-tone-table: wrote {} bytes to {}",
        src.len(),
        path.display()
    );
}
